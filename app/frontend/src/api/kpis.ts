import { apiClient } from './client';
import { IKpisDashboard, ISeguimientoFila, IAgendaItem } from '../types/kpi';

/** ISO week (YYYY-Www) for the dashboard week number of the current year. */
const toIsoWeek = (semana?: string | number): string | undefined => {
  if (semana === undefined || semana === '') return undefined;
  const week = Number(semana);
  if (!Number.isInteger(week) || week < 1 || week > 53) return undefined;
  return `${new Date().getFullYear()}-W${String(week).padStart(2, '0')}`;
};

interface WeeklyKpisResponse {
  week: string;
  scheduledVisits: number;
  completedVisits: number;
  effectivenessRate: number;
  quotedValue: number;
  closedOrders: number;
  routeBilling: number;
  weeklyGoal: { target: number; completed: number; percentage: number };
}

export const getDashboardKpis = async (
  _territorio?: string,
  semana?: string | number,
): Promise<IKpisDashboard> => {
  const { data } = await apiClient.get<WeeklyKpisResponse>('/dashboard/kpis', {
    params: { week: toIsoWeek(semana) },
  });
  return {
    programadas: data.scheduledVisits,
    realizadas: data.completedVisits,
    efectividad: data.effectivenessRate,
    valorCotizado: data.quotedValue,
    pedidos: data.closedOrders,
    facturacion: data.routeBilling,
    metaVisitas: data.weeklyGoal.target,
    completadasVisitas: data.weeklyGoal.completed,
    porcentajeCumplimiento: data.weeklyGoal.percentage,
  };
};

interface VisitTrackingRow {
  visitId: number;
  date: string;
  advisorName: string | null;
  territory: string | null;
  week: number;
  day: string;
  route: string | null;
  customer: string;
  municipality: string | null;
  customerType: string | null;
  potential: string | null;
  visitStatus: string;
  outcome: string | null;
  quoteNumber: string | null;
  quoteAmount: number;
  orderNumber: string | null;
  nextFollowUpDate: string | null;
}

const toTrackingStatus = (
  status?: string,
): ISeguimientoFila['estado_visita'] => {
  const s = (status || '').toUpperCase();
  if (['COMPLETED', 'VISITED', 'REALIZADA', 'VISITADO'].includes(s))
    return 'Visitado';
  if (['RESCHEDULED', 'REPROGRAMADA', 'REPROGRAMADO'].includes(s))
    return 'Reprogramado';
  if (['CANCELLED', 'CANCELADA', 'SIN_VISITAR', 'NOT_VISITED'].includes(s))
    return 'Sin visitar';
  if (['ORDER_CLOSED', 'PEDIDO_CERRADO'].includes(s)) return 'Pedido cerrado';
  return 'Pendiente';
};

const toPotential = (value: string | null): ISeguimientoFila['potencial'] =>
  value === 'Alto' || value === 'Bajo' ? value : 'Medio';

export const getSeguimientoVisitas = async (
  periodo: 'today' | 'week' | 'month' = 'week',
): Promise<ISeguimientoFila[]> => {
  const { data } = await apiClient.get<VisitTrackingRow[]>(
    '/visitas/seguimiento',
    { params: { periodo, limit: 100 } },
  );
  return data.map((row) => ({
    id: String(row.visitId),
    fecha: row.date,
    asesor: row.advisorName ?? '—',
    territorio: row.territory ?? '—',
    semana: row.week,
    dia: row.day,
    ruta: row.route ?? '—',
    cliente: row.customer,
    municipio: row.municipality ?? '—',
    tipo_cliente: row.customerType ?? '—',
    potencial: toPotential(row.potential),
    estado_visita: toTrackingStatus(row.visitStatus),
    resultado: row.outcome ?? '—',
    cotizacion: row.quoteNumber ?? '—',
    valor_cotizacion: row.quoteAmount,
    pedido: row.orderNumber ?? '—',
    proximo_seguimiento: row.nextFollowUpDate ?? '—',
  }));
};

interface AgendaItemResponse {
  id: number;
  clientId: number;
  clientName?: string;
  clientAddress?: string | null;
  address?: string | null;
  order?: number;
  visitOrder?: number;
  suggestedTime?: string | null;
  time?: string;
  visitStatus?: string;
  status?: string;
  potential?: string;
  objective?: string | null;
  latitude?: number | null;
  longitude?: number | null;
  contactName?: string | null;
  primaryContact?: { name: string } | null;
}

export const getAgendaDelDia = async (
  fecha?: string,
): Promise<IAgendaItem[]> => {
  const { data } = await apiClient.get<AgendaItemResponse[]>('/visits/agenda', {
    params: fecha ? { date: fecha } : undefined,
  });
  return data.map((item, idx) => ({
    id: String(item.id),
    orden: item.order ?? item.visitOrder ?? idx + 1,
    hora: item.suggestedTime || item.time || '—',
    cliente: item.clientName || `Cliente #${item.clientId}`,
    estado: toTrackingStatus(
      item.visitStatus || item.status,
    ) as IAgendaItem['estado'],
    contacto: item.primaryContact?.name || item.contactName || undefined,
    objetivo: item.objective || undefined,
    potencial: item.potential || undefined,
    latitud: Number(item.latitude),
    longitud: Number(item.longitude),
    direccion: item.address || item.clientAddress || undefined,
  }));
};

/** Downloads the tracking report generated by the backend (HU-18). */
export const downloadCsvReport = async (
  territorio: string,
  etiqueta: string | number,
  periodo: 'today' | 'week' | 'month' = 'week',
): Promise<void> => {
  const { data } = await apiClient.get<Blob>('/reportes/seguimiento.csv', {
    params: { periodo },
    responseType: 'blob',
  });
  const url = URL.createObjectURL(data);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute(
    'download',
    `Reporte_Comercial360_${territorio}_${etiqueta}.csv`,
  );
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};
